// write puts body in a new owner-words.md and returns its path.
func write(t *testing.T, body string) string {
	p := filepath.Join(t.TempDir(), "owner-words.md")
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

// A file as gang relay.mjs:47,159,173-174 writes it (uuid keys, else timestamp keys) gives each entry its fields and exact text.
func TestReadsGangFormat(t *testing.T) {
	p := write(t, "# The user's words\n\nDo not edit this file.\n\n<!-- owner-words uuid=3b1f6c2e-8a4d-4f0e-9c21-5d7e8f9a0b1c at=2026-11-01T12:00:00.000Z -->\n\n# go\t \n\n<!-- owner-words uuid=5c0d2e4f-1a2b-4c3d-8e9f-0a1b2c3d4e5f at=2026-11-01T12:03:00.000Z -->\n ok\t\n\n<!-- owner-words uuid=2026-11-01T12:05:00.000Z at=2026-11-01T12:05:00.000Z -->\n\n\n<!-- owner-words uuid=a9e8d7c6-b5a4-4321-8fed-cba987654321 at=unknown supersedes=2026-11-01T12:05:00.000Z -->\n\twait:\n\n\r\n- keep A\r\n <!-- owner-words uuid=f at=x -->\n<!-- owner-words uuid note -->\n<!--  owner-words uuid=g at=x -->\n<!-- owner-words  uuid=h at=x -->\n\n\n\n")
	want := []Entry{{"3b1f6c2e-8a4d-4f0e-9c21-5d7e8f9a0b1c", "2026-11-01T12:00:00.000Z", "", "\n# go\t "}, {"5c0d2e4f-1a2b-4c3d-8e9f-0a1b2c3d4e5f", "2026-11-01T12:03:00.000Z", "", " ok\t"}, {"2026-11-01T12:05:00.000Z", "2026-11-01T12:05:00.000Z", "", ""}, {"a9e8d7c6-b5a4-4321-8fed-cba987654321", "unknown", "2026-11-01T12:05:00.000Z", "\twait:\n\n\r\n- keep A\r\n <!-- owner-words uuid=f at=x -->\n<!-- owner-words uuid note -->\n<!--  owner-words uuid=g at=x -->\n<!-- owner-words  uuid=h at=x -->\n\n"}}
	if got, err := Read(p); err != nil || len(got) != 4 || got[0] != want[0] || got[1] != want[1] || got[2] != want[2] || got[3] != want[3] {
		t.Errorf("Read = %q (err %v), want %q", got, err, want)
	}
	for _, w := range want {
		if e, err := Get(p, w.ID); err != nil || e != w {
			t.Errorf("Get %s = %q (err %v), want %q", w.ID, e, err, w)
		}
	}
}

// Get of an id that no entry holds fails, also beside near ids (prefix, suffix, longer, other case) and in a missing file.
func TestGetMissing(t *testing.T) {
	if got, err := Read(filepath.Join(t.TempDir(), "none.md")); len(got) != 0 || err != nil {
		t.Errorf("Read of a missing file = %q (err %v)", got, err)
	}
	for p, want := range map[string]string{filepath.Join(t.TempDir(), "none.md"): "owner words: no entry u9", write(t, "<!-- owner-words uuid=u9x at=u9 -->\nhi\n\n<!-- owner-words uuid=u at=+01:00 supersedes=u9 -->\nhi\n\n<!-- owner-words uuid=U9 at=x supersedes=a_b -->\nhi\n\n<!-- owner-words uuid=x_u9 at=x -->\nhi\n\n<!-- owner-words uuid=9 at=x -->\nhi\n\n"): "owner words: no entry u9", "/": "read /: is a directory"} {
		if _, err := Get(p, "u9"); err == nil || err.Error() != want {
			t.Errorf("Get u9 in %s: err %v", p, err)
		}
	}
}

// A line that starts like a header but breaks its form fails Read, and so Get, before or after a good entry.
func TestBadHeaderFails(t *testing.T) {
	for i, tail := range []string{"u1 at=x", "u1 -->", "u1 at=x by=y -->", "u1 at=x --> y", " at=x -->", "u1 u2 at=x -->", "u1 at= -->", "u1 at=x supersedes= -->", "u1 at=x supersedes=a b -->", "u1  at=x -->", "u1 at=x  supersedes=a -->", "u1 at=x  -->", "u1 at=x --> ", "u1 at=x supersedes=a supersedes=b -->", "u1\tx at=y -->", "u1 at=x\ty -->", "u1 at=x supersedes=a\tb -->", "u1 at=x -->\r", ""} {
		p := write(t, []string{"intro\n", "<!-- owner-words uuid=u0 at=x -->\nhi\n"}[i%2]+"<!-- owner-words uuid="+tail+"\ntext\n\n")
		if _, err := Get(p, "u1"); err == nil || err.Error() != "owner words: "+p+" line "+string(rune('2'+i%2))+": bad header" {
			t.Errorf("tail %q: err %v", tail, err)
		}
	}
}

// Each one-byte edit of a header line reads as text once it loses the header start, else as a bad header or as the header that its fields rebuild.
func TestHeaderEdits(t *testing.T) {
	h := "<!-- owner-words uuid=a at=b supersedes=c -->"
	for k := range h {
		for _, s := range []string{h[:k] + h[k+1:], h[:k] + h[k:k+1] + h[k:], h[:k] + "\t" + h[k+1:], h[:k] + ":" + h[k+1:], h[:k] + " " + h[k:], h[:k] + strings.ToUpper(h[k:k+1]) + h[k+1:]} {
			if g, err := Read(write(t, s+"\n")); !strings.HasPrefix(s, "<!-- owner-words uuid=") && (err != nil || len(g) != 0) || strings.HasPrefix(s, "<!-- owner-words uuid=") && err == nil && (len(g) != 1 || "<!-- owner-words uuid="+g[0].ID+" at="+g[0].At+strings.Repeat(" supersedes="+g[0].Supersedes, min(len(g[0].Supersedes), 1))+" -->" != s) {
				t.Errorf("%q reads as %q (err %v)", s, g, err)
			}
		}
	}
}
