"""Tests for scripts/relay.mjs, the relay helper of the gang coordinator.

`words` copies the messages that the user typed from a session transcript
into run/owner-words.md, byte for byte. `prompt` writes the kickoff of the
next session and prints the command that starts it. `mute` silences the relay
hook for this session. The fixtures copy the entry shapes of real Claude Code
transcripts and live in temp dirs. The suite skips when node is not on PATH.
"""

import json
import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
SCRIPT = SKILL / "scripts" / "relay.mjs"
NODE = shutil.which("node")
MARKER = "gang relay kickoff:"
HEADER = ("# The user's words\n\nrelay.mjs copies each message that the user typed in a coordinator "
          "session here, byte for byte. Do not edit this file.\n\n")
# Non-ASCII text, built from code points so that no tool rewrites an escape.
HELLO = chr(0x4F60) + chr(0x597D) + ", " + chr(0x4E16) + chr(0x754C)
HUMAN = {"kind": "human"}


def typed(uuid, text, parent="p0", mode="acceptEdits", source="typed"):
    return {"type": "user", "uuid": uuid, "parentUuid": parent, "timestamp": "2026-01-02T03:04:05.000Z",
            "isSidechain": False, "permissionMode": mode, "origin": HUMAN, "promptSource": source,
            "message": {"role": "user", "content": text}}


def queued(uuid, text, origin=HUMAN):
    return {"type": "attachment", "uuid": uuid, "parentUuid": "pq", "timestamp": "2026-01-02T03:05:00.000Z",
            "isSidechain": False, "attachment": {"type": "queued_command", "origin": origin, "prompt": text}}


def entries():
    """A transcript with one entry of each kind that `words` must tell apart."""
    return [
        {"type": "user", "uuid": "u-meta", "isMeta": True, "isSidechain": False, "origin": HUMAN,
         "message": {"role": "user", "content": "<local-command-caveat>Caveat</local-command-caveat>"}},
        {"type": "user", "uuid": "u-cmd", "isSidechain": False, "origin": HUMAN,
         "message": {"role": "user", "content": "<command-message>gang</command-message>\n"
                                                "<command-name>/monet:gang</command-name>"}},
        {"type": "agent-name", "agentName": "gang demo"},
        typed("u-1", "Build the demo.\n\n- keep it small\n", parent="p0"),
        {"type": "assistant", "uuid": "a-1", "isSidechain": False,
         "message": {"model": "claude-opus-5-5",
                     "content": [{"type": "tool_use", "id": "toolu_1", "name": "Bash", "input": {}}]}},
        {"type": "assistant", "uuid": "a-side", "isSidechain": True, "message": {"model": "claude-haiku-5-5"}},
        {"type": "user", "uuid": "u-tool", "isSidechain": False, "origin": HUMAN,
         "message": {"role": "user", "content": [{"type": "tool_result", "tool_use_id": "toolu_1", "content": "ok"},
                                                 {"type": "text", "text": "typed-looking output"}]}},
        typed("u-sugg", "Accept the suggestion.", parent="ps", source="suggestion_accepted"),
        typed("u-2", [{"type": "text", "text": HELLO}, {"type": "image", "source": {}},
                      {"type": "text", "text": "second block"}], parent="p1"),
        dict(typed("u-side", "a subagent prompt"), isSidechain=True),
        queued("q-1", "Also add a README."),
        queued("q-2", "<task-notification>done</task-notification>", origin={"kind": "task-notification"}),
        typed("u-q", "Typed while it worked.", parent="pq2", source="queued"),
        typed("u-2b", "Second try.", parent="p1"),
        typed("u-2c", "Third try.", parent="p1"),
        typed("u-kick", MARKER + " run demo, from session gang demo (s0).\n\nGo on.", parent="p9"),
    ]


@unittest.skipUnless(NODE, "node is not on PATH")
class RelayScript(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.tmp = Path(tmp.name)
        self.config_dir = self.tmp / "config"
        self.transcript = self.config_dir / "projects" / "-demo" / "sess-1.jsonl"
        self.transcript.parent.mkdir(parents=True)
        self.write_transcript(entries())
        self.state_dir = self.tmp / "state"
        self.state_dir.mkdir()
        self.dir = self.tmp / "repo" / ".planning" / "gang" / "demo"
        (self.dir / "run" / "handoff").mkdir(parents=True)
        self.words = self.dir / "run" / "owner-words.md"

    def write_transcript(self, rows):
        self.transcript.write_text("".join(json.dumps(r) + "\n" for r in rows), encoding="utf-8")

    def run_script(self, *args, env=None, code=0, drop=()):
        base = {k: v for k, v in os.environ.items()
                if k not in ("CLAUDE_CODE_SESSION_ID", "CLAUDE_CONFIG_DIR", "CLAUDE_JOB_DIR", "CLAUDE_EFFORT",
                             "CLAUDE_RELAY_STATE_DIR")}
        base.update({"CLAUDE_CODE_SESSION_ID": "sess-1", "CLAUDE_CONFIG_DIR": str(self.config_dir),
                     "CLAUDE_RELAY_STATE_DIR": str(self.state_dir)})
        base.update(env or {})
        for name in drop:
            base.pop(name, None)
        proc = subprocess.run([NODE, str(SCRIPT), *args], capture_output=True, text=True,
                              env=base, timeout=30, check=False)
        self.assertEqual(proc.returncode, code, proc.stdout + proc.stderr)
        return proc

    def words_out(self):
        return self.run_script("words", "--out", str(self.words)).stdout

    # ---- words

    def test_words_copies_the_messages_of_the_user(self):
        self.assertEqual(self.words_out(),
                         f"owner-words: 7 new, 7 in {self.words} (new: u-1 u-sugg u-2 q-1 u-q u-2b u-2c)\n")
        text = self.words.read_text(encoding="utf-8")
        self.assertTrue(text.startswith(HEADER), text[:200])
        self.assertIn("-->\nBuild the demo.\n\n- keep it small\n\n", text)
        self.assertIn("-->\n" + HELLO + "\n\nsecond block\n\n", text)
        self.assertEqual(text.count("Also add a README."), 1)
        # Each edit replaces the one before it, not the first one.
        self.assertIn("<!-- owner-words uuid=u-2b at=2026-01-02T03:04:05.000Z supersedes=u-2 -->\nSecond try.\n",
                      text)
        self.assertIn("<!-- owner-words uuid=u-2c at=2026-01-02T03:04:05.000Z supersedes=u-2b -->\nThird try.\n",
                      text)
        for absent in ("Caveat", "/monet:gang", "typed-looking output", "a subagent prompt",
                       "task-notification", MARKER):
            with self.subTest(absent=absent):
                self.assertNotIn(absent, text)
        order = [text.index(s) for s in ("Build the demo.", "Accept the suggestion.", HELLO, "Also add a README.",
                                         "Typed while it worked.", "Second try.", "Third try.")]
        self.assertEqual(order, sorted(order))

    def test_words_appends_only_new_messages(self):
        self.words_out()
        first = self.words.read_text(encoding="utf-8")
        self.assertEqual(self.words_out(), f"owner-words: 0 new, 7 in {self.words}\n")
        self.assertEqual(self.words.read_text(encoding="utf-8"), first)
        self.write_transcript(entries() + [typed("u-3", "Use port 8080.", parent="p3")])
        self.assertEqual(self.words_out(), f"owner-words: 1 new, 8 in {self.words} (new: u-3)\n")
        text = self.words.read_text(encoding="utf-8")
        self.assertTrue(text.startswith(first))
        self.assertEqual(text.count("Use port 8080."), 1)

    def test_words_keeps_messages_from_an_earlier_session(self):
        self.words.write_text("# The user's words\n\n<!-- owner-words uuid=u-old at=x -->\nOld rule.\n\n",
                              encoding="utf-8")
        self.words_out()
        text = self.words.read_text(encoding="utf-8")
        self.assertTrue(text.startswith("# The user's words\n\n<!-- owner-words uuid=u-old at=x -->\nOld rule.\n"))
        self.assertEqual(text.count("# The user's words"), 1)
        self.assertIn("Build the demo.", text)

    def test_words_takes_an_explicit_transcript(self):
        other = self.tmp / "other.jsonl"
        other.write_text(json.dumps(typed("u-9", "From the other file.")) + "\n", encoding="utf-8")
        self.run_script("words", "--out", str(self.words), "--transcript", str(other))
        self.assertIn("From the other file.", self.words.read_text(encoding="utf-8"))

    def test_words_fails_when_the_user_never_wrote(self):
        self.write_transcript([e for e in entries() if e.get("origin") != HUMAN and e["type"] != "attachment"])
        proc = self.run_script("words", "--out", str(self.words), code=1)
        self.assertIn("no message from the user", proc.stderr)
        self.assertFalse(self.words.exists())

    def test_words_after_a_respawn_keeps_the_file(self):
        # A respawned session writes a new transcript that may hold no message from the user.
        self.words.write_text(HEADER + "<!-- owner-words uuid=u-old at=x -->\nOld rule.\n\n", encoding="utf-8")
        self.write_transcript([{"type": "agent-name", "agentName": "gang demo"}])
        self.assertEqual(self.words_out(), f"owner-words: 0 new, 1 in {self.words}\n")

    def test_words_in_a_session_started_by_a_command(self):
        self.write_transcript([entries()[1]])
        self.assertEqual(self.words_out(), f"owner-words: 0 new, 0 in {self.words}\n")
        self.assertFalse(self.words.exists())

    def test_words_in_a_relayed_session_with_only_its_kickoff(self):
        self.write_transcript([typed("u-kick", MARKER + " run demo, from session gang demo (s0).")])
        self.assertEqual(self.words_out(), f"owner-words: 0 new, 0 in {self.words}\n")

    def test_words_fails_without_a_transcript(self):
        proc = self.run_script("words", "--out", str(self.words), env={"CLAUDE_CODE_SESSION_ID": "missing"},
                               code=2)
        self.assertIn("no transcript", proc.stderr)

    def test_an_unexpected_failure_exits_3(self):
        proc = self.run_script("words", "--out", str(self.dir), code=3)
        self.assertTrue(proc.stderr.startswith("relay: "), proc.stderr)
        self.assertEqual(proc.stderr.count("\n"), 1)

    # ---- prompt

    def handoff(self):
        path = self.dir / "run" / "handoff" / "2026-01-02-0304.md"
        path.write_text("# Handoff\n", encoding="utf-8")
        (self.dir / "run" / "standing.md").write_text("- Only the coordinator pushes.\n", encoding="utf-8")
        self.words.write_text(HEADER + HELLO + "\n", encoding="utf-8")
        return path

    def job(self, name, flags):
        job = self.tmp / "job"
        job.mkdir(exist_ok=True)
        (job / "state.json").write_text(json.dumps({"name": name, "sessionId": "sess-1",
                                                    "respawnFlags": flags}), encoding="utf-8")
        return {"CLAUDE_JOB_DIR": str(job)}

    def hook_state(self, **fields):
        (self.state_dir / "monet-relay-sess-1.json").write_text(json.dumps(fields), encoding="utf-8")

    def prompt(self, *extra, env=None, code=0):
        path = self.handoff()
        proc = self.run_script("prompt", "--dir", str(self.dir), "--slug", "demo", "--handoff", str(path),
                               *extra, env=env, code=code)
        return proc, path.with_name("2026-01-02-0304.prompt.txt")

    def test_prompt_writes_the_kickoff_and_prints_the_command(self):
        self.hook_state(permissionMode="acceptEdits")
        env = self.job("gang demo 2", ["--effort", "max", "--name", "gang demo 2", "--model", "opus",
                                       "--plugin-dir", "/opt/my plugins", "--permission-mode", "auto",
                                       "--session-id", "old-id", "--continue", "--resume=old-id"])
        proc, prompt = self.prompt("--merge-on-green", env=env)
        kickoff = f"{MARKER} run demo, from session gang demo 2 (sess-1)."
        argv_prompt = f"'{kickoff}\n\nRead {prompt} with the Read tool first, and follow it.'"
        self.assertEqual(proc.stdout, "claude --bg --name 'gang demo 3' --effort max --model opus "
                                      f"--plugin-dir '/opt/my plugins' --permission-mode acceptEdits {argv_prompt}\n")
        text = prompt.read_text(encoding="utf-8")
        self.assertTrue(text.startswith(kickoff + "\n\n"), text)
        self.assertIn("`run --slug demo --merge-on-green`", text)
        self.assertIn('"Resume in a new session"', text)
        self.assertIn(f"First read the handoff at {self.dir / 'run' / 'handoff' / '2026-01-02-0304.md'}.", text)
        self.assertIn("## Standing orders (run/standing.md)\n\n- Only the coordinator pushes.\n", text)
        self.assertIn("## Past words of the user (run/owner-words.md)\n\nThis is history: ", text)
        self.assertTrue(text.endswith("still open.\n\n" + HEADER + HELLO + "\n"), text[-300:])

    def test_prompt_mode_comes_from_the_best_source(self):
        env = self.job("gang demo", ["--permission-mode", "plan"])
        self.hook_state(permissionMode="auto")
        cases = [((), "auto"), (("--mode", "manual"), "manual")]
        for extra, want in cases:
            with self.subTest(extra=extra):
                proc, _ = self.prompt(*extra, env=env)
                self.assertIn(f" --permission-mode {want} '", proc.stdout)
        (self.state_dir / "monet-relay-sess-1.json").unlink()
        proc, _ = self.prompt(env=env)
        self.assertIn(" --permission-mode plan '", proc.stdout)
        proc, _ = self.prompt()
        self.assertIn(" --permission-mode acceptEdits '", proc.stdout)

    def test_prompt_without_a_job_dir(self):
        # The model comes from the newest main-chain request, as an alias.
        proc, prompt = self.prompt(env={"CLAUDE_EFFORT": "high"})
        self.assertTrue(proc.stdout.startswith("claude --bg --name 'gang demo 2' --effort high --model opus "
                                               "--permission-mode acceptEdits '"), proc.stdout)
        self.assertIn("`run --slug demo`", prompt.read_text(encoding="utf-8"))

    def test_prompt_needs_a_permission_mode(self):
        self.write_transcript([{"type": "agent-name", "agentName": "gang demo"}])
        proc, _ = self.prompt(code=2)
        self.assertIn("no permission mode", proc.stderr)
        proc, _ = self.prompt("--mode", "acceptEdits")
        self.assertIn(" --permission-mode acceptEdits '", proc.stdout)

    def test_prompt_without_a_transcript(self):
        self.hook_state(permissionMode="auto")
        proc, prompt = self.prompt(env={"CLAUDE_CODE_SESSION_ID": "sess-1", "CLAUDE_CONFIG_DIR": str(self.tmp / "no")})
        self.assertTrue(proc.stdout.startswith("claude --bg --name 'gang demo 2' --permission-mode auto '"),
                        proc.stdout)
        self.assertTrue(prompt.exists())

    def test_prompt_names_from_the_slug_as_a_last_resort(self):
        self.write_transcript([typed("u-1", "Build it.", mode="manual")])
        proc, _ = self.prompt()
        self.assertTrue(proc.stdout.startswith("claude --bg --name 'gang demo 2' --permission-mode manual '"),
                        proc.stdout)

    def test_prompt_quotes_a_name_with_a_quote(self):
        proc, _ = self.prompt(env=self.job("it's 9", ["--model", "sonnet"]))
        self.assertTrue(proc.stdout.startswith("claude --bg --name 'it'\\''s 10' --model sonnet "), proc.stdout)

    def test_prompt_marks_missing_files_as_none(self):
        path = self.dir / "run" / "handoff" / "h.md"
        path.write_text("# Handoff\n", encoding="utf-8")
        self.run_script("prompt", "--dir", str(self.dir), "--slug", "demo", "--handoff", str(path))
        text = path.with_name("h.prompt.txt").read_text(encoding="utf-8")
        self.assertIn("## Standing orders (run/standing.md)\n\n(none)\n", text)
        self.assertIn("still open.\n\n(none)\n", text)

    def test_prompt_needs_the_handoff(self):
        proc = self.run_script("prompt", "--dir", str(self.dir), "--slug", "demo",
                               "--handoff", str(self.dir / "run" / "handoff" / "none.md"), code=2)
        self.assertIn("no handoff", proc.stderr)

    # ---- mute

    def test_mute_marks_the_hook_state(self):
        state = self.state_dir / "monet-relay-sess-1.json"
        self.assertEqual(self.run_script("mute").stdout, f"relay: muted {state}\n")
        self.assertEqual(json.loads(state.read_text(encoding="utf-8")), {"muted": True})
        self.hook_state(fired=True, pct=91)
        self.run_script("mute")
        self.assertEqual(json.loads(state.read_text(encoding="utf-8")), {"fired": True, "pct": 91, "muted": True})

    def test_mute_needs_a_session_id(self):
        proc = self.run_script("mute", code=2, drop=("CLAUDE_CODE_SESSION_ID",))
        self.assertIn("CLAUDE_CODE_SESSION_ID", proc.stderr)

    def test_usage_errors(self):
        for args in ((), ("words",), ("prompt", "--slug", "demo"), ("nope",), ("words", "--bogus", "x")):
            with self.subTest(args=args):
                self.assertIn("usage:", self.run_script(*args, code=2).stderr)


if __name__ == "__main__":
    unittest.main()
