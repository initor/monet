#!/usr/bin/env node
// relay.mjs: the relay helper of the gang coordinator.
//
//   node relay.mjs words --out <file> [--transcript <path>]
//   node relay.mjs prompt --dir <dir> --slug <slug> --handoff <file> [--merge-on-green]
//                  [--mode <permission mode>] [--transcript <path>]
//   node relay.mjs mute
//
// words appends each message that the user typed in this session to <file>,
// byte for byte, and skips the messages that <file> holds already. It takes
// typed prompts, accepted suggestions, and the messages typed while a turn
// ran, and it skips slash commands, relay kickoff prompts, and the prompts of
// subagents. A message
// that replaces an earlier one, after an edit or a rewind, gets
// supersedes=<uuid> in its header. It prints
// "owner-words: <new> new, <total> in <file>", then the uuids of the new
// entries. Exit 1: the transcript holds no message from the user and <file>
// holds none either, so it is the wrong transcript or its format changed.
//
// prompt writes the kickoff of the next coordinator session beside the
// handoff, as <handoff without .md>.prompt.txt, with run/standing.md and
// run/owner-words.md in it word for word. It prints the claude --bg command
// that starts the next session, whose own prompt only names that file. The
// permission mode comes from --mode, else from the state of the relay hook,
// else from the respawn flags of the job, else from the transcript. Exit 2
// when no source has one.
//
// mute marks the relay hook state of this session as muted, so that the hook
// gives this session no more notices.
//
// CLAUDE_CODE_SESSION_ID names the transcript and the hook state of this
// session. The transcript is under <config dir>/projects/*/, where the config
// dir is CLAUDE_CONFIG_DIR, else .claude in the home dir. The hook state is
// <state dir>/monet-relay-<id>.json, where the state dir is
// CLAUDE_RELAY_STATE_DIR, else /tmp. Exit 2 also means a usage error or a
// missing input, and exit 3 means any other failure.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import readline from 'node:readline';

const MARKER = 'gang relay kickoff:';
const WORDS_HEADER = "# The user's words\n\n" +
  'relay.mjs copies each message that the user typed in a coordinator session here, byte for byte. ' +
  'Do not edit this file.\n\n';
const ENTRY = /^<!-- owner-words uuid=(\S+) /gm;
const COMMAND = /^\s*<(command-message|command-name)>/;
const VALUE_FLAGS = ['--out', '--transcript', '--dir', '--slug', '--handoff', '--mode'];
// Respawn flags that the next session must not reuse: the relay sets its own
// name and mode, and the next session is a new one, not a resumed one.
const DROPPED_WITH_VALUE = ['--name', '-n', '--permission-mode', '--session-id', '--resume', '-r'];
const DROPPED_ALONE = ['--continue', '-c', '--fork-session', '--inherit-permission-mode'];
const MODEL_ALIASES = ['opus', 'sonnet', 'haiku', 'fable'];
const USAGE = 'usage: relay.mjs words --out <file> [--transcript <path>]\n' +
  '       relay.mjs prompt --dir <dir> --slug <slug> --handoff <file> [--merge-on-green] [--mode <mode>] ' +
  '[--transcript <path>]\n' +
  '       relay.mjs mute';

class Fail extends Error {
  constructor(code, message) {
    super(message);
    this.code = code;
  }
}

function parseArgs(argv) {
  const [verb, ...rest] = argv;
  const opts = {};
  for (let i = 0; i < rest.length; i++) {
    const arg = rest[i];
    if (arg === '--merge-on-green') {
      opts.mergeOnGreen = true;
    } else if (VALUE_FLAGS.includes(arg) && i + 1 < rest.length) {
      opts[arg.slice(2)] = rest[++i];
    } else {
      throw new Fail(2, USAGE);
    }
  }
  return { verb, opts };
}

function sessionId() {
  const sid = process.env.CLAUDE_CODE_SESSION_ID || '';
  return sid && !/[/\\]|\.\./.test(sid) ? sid : '';
}

function statePath() {
  const sid = sessionId();
  return sid ? path.join(process.env.CLAUDE_RELAY_STATE_DIR || '/tmp', `monet-relay-${sid}.json`) : '';
}

function readJSON(file) {
  try { return JSON.parse(fs.readFileSync(file, 'utf8')) || {}; } catch (e) { return {}; }
}

function transcriptPath(opts) {
  if (opts.transcript) {
    if (!fs.existsSync(opts.transcript)) throw new Fail(2, `relay: no transcript at ${opts.transcript}`);
    return opts.transcript;
  }
  const sid = sessionId();
  const projects = path.join(process.env.CLAUDE_CONFIG_DIR || path.join(os.homedir(), '.claude'), 'projects');
  if (sid && fs.existsSync(projects)) {
    for (const dir of fs.readdirSync(projects)) {
      const file = path.join(projects, dir, `${sid}.jsonl`);
      if (fs.existsSync(file)) return file;
    }
  }
  throw new Fail(2, `relay: no transcript for session ${sid || '(CLAUDE_CODE_SESSION_ID is not set)'} under ${projects}`);
}

// entries streams the parsed lines of a transcript, so that a large one
// never sits in memory as a whole.
async function* entries(file) {
  const lines = readline.createInterface({ input: fs.createReadStream(file, { encoding: 'utf8' }), crlfDelay: Infinity });
  for await (const line of lines) {
    if (!line) continue;
    let e;
    try { e = JSON.parse(line); } catch (err) { continue; }
    if (e && typeof e === 'object') yield e;
  }
}

function textOf(content) {
  if (typeof content === 'string') return content;
  if (!Array.isArray(content) || content.some(b => b && b.type === 'tool_result')) return null;
  const parts = content.filter(b => b && b.type === 'text' && typeof b.text === 'string').map(b => b.text);
  return parts.length ? parts.join('\n\n') : null;
}

// fromUser returns the text of a message that the user typed in a main-chain
// entry, or null. A prompt is a user entry. A message typed while a turn runs
// is a queued_command attachment.
function fromUser(e) {
  if (e.isSidechain || e.isMeta) return null;
  if (e.type === 'user') {
    if (!((e.origin && e.origin.kind === 'human') || e.promptSource === 'typed')) return null;
    return textOf(e.message && e.message.content);
  }
  const a = e.type === 'attachment' ? e.attachment : null;
  if (a && a.type === 'queued_command' && a.origin && a.origin.kind === 'human') return textOf(a.prompt);
  return null;
}

async function words(opts) {
  if (!opts.out) throw new Fail(2, USAGE);
  const file = transcriptPath(opts);
  const old = fs.existsSync(opts.out) ? fs.readFileSync(opts.out, 'utf8') : '';
  const have = new Set([...old.matchAll(ENTRY)].map(m => m[1]));
  const byParent = new Map();
  const fresh = [];
  let fromHuman = 0;
  for await (const e of entries(file)) {
    const text = fromUser(e);
    if (text === null) continue;
    fromHuman++;
    if (COMMAND.test(text) || text.startsWith(MARKER)) continue;
    const key = e.uuid || e.promptId || e.timestamp;
    if (!key) continue;
    // Messages with one parent are edits of each other: each replaces the one before it.
    const parent = typeof e.parentUuid === 'string' ? e.parentUuid : '';
    const earlier = parent ? byParent.get(parent) : undefined;
    if (parent) byParent.set(parent, key);
    if (have.has(key)) continue;
    have.add(key);
    fresh.push({ key, at: e.timestamp || 'unknown', text, supersedes: earlier });
  }
  if (fromHuman === 0 && have.size === 0) {
    throw new Fail(1, 'relay: no message from the user in the transcript, so it is the wrong transcript or its format changed');
  }
  if (fresh.length) {
    const body = fresh.map(f => `<!-- owner-words uuid=${f.key} at=${f.at}` +
      `${f.supersedes ? ` supersedes=${f.supersedes}` : ''} -->\n${f.text}\n\n`).join('');
    fs.mkdirSync(path.dirname(opts.out), { recursive: true });
    fs.appendFileSync(opts.out, (old ? '' : WORDS_HEADER) + body);
  }
  const added = fresh.length ? ` (new: ${fresh.map(f => f.key).join(' ')})` : '';
  return `owner-words: ${fresh.length} new, ${have.size} in ${opts.out}${added}`;
}

function shellQuote(s) {
  return `'${String(s).replace(/'/g, "'\\''")}'`;
}

function token(s) {
  return /^[A-Za-z0-9._=-]+$/.test(s) ? s : shellQuote(s);
}

// nextName raises a trailing number by one, or adds " 2".
function nextName(name) {
  const m = /^(.*\S) (\d+)$/.exec(name);
  return m ? `${m[1]} ${Number(m[2]) + 1}` : `${name} 2`;
}

function flagValue(flags, name) {
  const i = flags.indexOf(name);
  if (i >= 0 && i + 1 < flags.length) return flags[i + 1];
  const joined = flags.find(f => f.startsWith(`${name}=`));
  return joined ? joined.slice(name.length + 1) : '';
}

// carriedFlags keeps the respawn flags of the job that the next session
// needs, such as --model and --plugin-dir.
function carriedFlags(flags) {
  const kept = [];
  for (let i = 0; i < flags.length; i++) {
    if (DROPPED_WITH_VALUE.includes(flags[i])) { i++; continue; }
    if (DROPPED_ALONE.includes(flags[i])) continue;
    if ([...DROPPED_WITH_VALUE, ...DROPPED_ALONE].some(f => flags[i].startsWith(`${f}=`))) continue;
    kept.push(flags[i]);
  }
  return kept;
}

// modelAlias turns a model id such as claude-opus-5-5 into its alias.
function modelAlias(id) {
  return MODEL_ALIASES.find(a => id.includes(`-${a}-`) || id === a) || id;
}

async function newestFields(file) {
  const out = {};
  if (!file) return out;
  for await (const e of entries(file)) {
    for (const k of ['agentName', 'customTitle', 'permissionMode']) {
      if (typeof e[k] === 'string' && e[k]) out[k] = e[k];
    }
    const model = e.type === 'assistant' && !e.isSidechain && e.message && e.message.model;
    if (typeof model === 'string' && model && !model.startsWith('<')) out.model = model;
  }
  return out;
}

async function prompt(opts) {
  if (!opts.dir || !opts.slug || !opts.handoff) throw new Fail(2, USAGE);
  if (!fs.existsSync(opts.handoff)) throw new Fail(2, `relay: no handoff at ${opts.handoff}`);
  const job = process.env.CLAUDE_JOB_DIR ? readJSON(path.join(process.env.CLAUDE_JOB_DIR, 'state.json')) : {};
  let file = '';
  try { file = transcriptPath(opts); } catch (e) { if (!(e instanceof Fail)) throw e; }
  const seen = await newestFields(file);
  const state = statePath() ? readJSON(statePath()) : {};
  const flags = Array.isArray(job.respawnFlags) ? job.respawnFlags.map(String) : [];
  const mode = opts.mode || (typeof state.permissionMode === 'string' && state.permissionMode) ||
    flagValue(flags, '--permission-mode') || seen.permissionMode || '';
  if (!mode) throw new Fail(2, 'relay: no permission mode found for this session, so pass --mode <mode>');

  const name = (typeof job.name === 'string' && job.name) || seen.agentName || seen.customTitle || `gang ${opts.slug}`;
  const sid = sessionId() || (typeof job.sessionId === 'string' && job.sessionId) || 'unknown';
  const args = `run --slug ${opts.slug}${opts.mergeOnGreen ? ' --merge-on-green' : ''}`;
  const kickoff = `${MARKER} run ${opts.slug}, from session ${name} (${sid}).`;
  const read = f => (fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '');
  const section = (title, intro, body) => `## ${title}\n\n${intro}` +
    (body.trim() ? body.replace(/\n*$/, '\n') : '(none)\n');
  const text = `${kickoff}\n\n` +
    'The handoff relay started this session, and the session named above has stopped working. ' +
    `Invoke the monet:gang skill with the arguments \`${args}\`. In that run, follow ` +
    '"Resume in a new session" in the gang reference/coordinator.md. ' +
    `First read the handoff at ${path.resolve(opts.handoff)}.\n\n` +
    section('Standing orders (run/standing.md)', '', read(path.join(opts.dir, 'run', 'standing.md'))) + '\n' +
    section('Past words of the user (run/owner-words.md)',
      'This is history: each message that the user typed in an earlier session of this run, for context. ' +
      'Keep following the rules in it, unless a later entry replaces them. The handoff says which requests ' +
      'are still open.\n\n',
      read(path.join(opts.dir, 'run', 'owner-words.md')));
  const out = path.resolve(opts.handoff.replace(/\.md$/, '') + '.prompt.txt');
  fs.writeFileSync(out, text);

  const parts = ['claude', '--bg', '--name', shellQuote(nextName(name)), ...carriedFlags(flags).map(token)];
  if (!flagValue(flags, '--effort') && process.env.CLAUDE_EFFORT) parts.push('--effort', token(process.env.CLAUDE_EFFORT));
  if (!flagValue(flags, '--model') && seen.model) parts.push('--model', token(modelAlias(seen.model)));
  parts.push('--permission-mode', token(mode));
  parts.push(shellQuote(`${kickoff}\n\nRead ${out} with the Read tool first, and follow it.`));
  return parts.join(' ');
}

function mute() {
  const file = statePath();
  if (!file) throw new Fail(2, 'relay: CLAUDE_CODE_SESSION_ID is not set, so this session has no hook state to mute');
  const state = readJSON(file);
  state.muted = true;
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, JSON.stringify(state));
  fs.renameSync(tmp, file);
  return `relay: muted ${file}`;
}

try {
  const { verb, opts } = parseArgs(process.argv.slice(2));
  let out;
  if (verb === 'words') out = await words(opts);
  else if (verb === 'prompt') out = await prompt(opts);
  else if (verb === 'mute') out = mute();
  else throw new Fail(2, USAGE);
  console.log(out);
} catch (e) {
  if (e instanceof Fail) {
    process.stderr.write(`${e.message}\n`);
    process.exit(e.code);
  }
  process.stderr.write(`relay: ${e && e.message ? e.message : e}\n`);
  process.exit(3);
}
